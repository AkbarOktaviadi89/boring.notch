import AppKit
import Combine
import Defaults

/// Notices copied text that Dev Tools can decode and offers it on the closed notch for a few seconds.
/// The clipboard is only read when it changes, and nothing is stored.
@MainActor
final class ClipboardWatcher: ObservableObject {
    static let shared = ClipboardWatcher()

    struct Suggestion: Equatable {
        let text: String
        let kind: ClipboardKind
    }

    @Published private(set) var suggestion: Suggestion?

    static let visibleDuration: Duration = .seconds(6)

    /// Marked by password managers and other apps that don't want clipboard tools to look
    /// (see nspasteboard.org)
    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var hideTask: Task<Void, Never>?

    private init() {}

    private var settingsTask: Task<Void, Never>?

    /// Polls only while suggestions are on; turning them off in Settings stops the timer
    func start() {
        guard settingsTask == nil else { return }
        settingsTask = Task { [weak self] in
            for await (suggestions, devTools) in Defaults.updates(.clipboardSuggestions, .devToolsEnabled) {
                self?.setPolling(suggestions && devTools)
            }
        }
    }

    private func setPolling(_ on: Bool) {
        guard on != (timer != nil) else { return }
        if on {
            // Changes made while off don't count as new
            lastChangeCount = NSPasteboard.general.changeCount
            let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
                Task { @MainActor in
                    self?.poll()
                }
            }
            timer.tolerance = 0.3
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            timer?.invalidate()
            timer = nil
            dismiss()
        }
    }

    /// Call right after the app itself writes to the clipboard, so its own results aren't offered back
    func ignoreCurrentChange() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    /// Loads the suggestion into Dev Tools and makes it the current tab. Returns false when there is none.
    @discardableResult
    func accept() -> Bool {
        guard let suggestion, Defaults[.devToolsEnabled] else { return false }
        DevToolsManager.shared.load(suggestion.text, kind: suggestion.kind)
        BoringViewCoordinator.shared.currentView = .devTools
        dismiss()
        return true
    }

    func dismiss() {
        hideTask?.cancel()
        suggestion = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard Defaults[.clipboardSuggestions], Defaults[.devToolsEnabled] else { return }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.skippedTypes.contains),
              let text = pasteboard.string(forType: .string),
              let kind = ClipboardDetector.detect(text)
        else {
            dismiss()
            return
        }

        suggestion = Suggestion(text: text, kind: kind)
        hideTask?.cancel()
        hideTask = Task { [weak self] in
            try? await Task.sleep(for: Self.visibleDuration)
            guard !Task.isCancelled else { return }
            self?.suggestion = nil
        }
    }
}
